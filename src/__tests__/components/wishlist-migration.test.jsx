import { beforeEach, afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import DataMigrator from '../../components/DataMigrator';
import SettingsPage from '../../pages/Settings/SettingsPage';
import { migrateData } from '../../services/firestoreService';
import { STORAGE_KEY } from '../../utils/constants';
import { normalizeBackupData } from '../../utils/backupHelpers';
import { downloadJson, downloadCsvZip } from '../../services/exportService';
vi.mock('../../services/firestoreService', () => ({ migrateData: vi.fn() }));
vi.mock('../../services/exportService', async original => ({ ...await original(), downloadJson: vi.fn(), downloadCsvZip: vi.fn() }));
vi.mock('../../utils/backupHelpers', async original => { const actual = await original(); return { ...actual, normalizeBackupData: vi.fn(actual.normalizeBackupData) }; });
beforeEach(() => { localStorage.clear(); vi.clearAllMocks(); });
afterEach(cleanup);
const timestamp = '2026-10-01T00:00:00.000Z';
const wishlistGroups = [{ id: 'g1', title: 'Meja', targetBudget: 100, targetDate: '2026-12-31', createdAt: timestamp, updatedAt: timestamp, items: [{ id: 'i1', groupId: 'g1', name: 'Lampu', price: 20, priority: 'medium', marketplaceName: '', productUrl: '', createdAt: timestamp, updatedAt: timestamp }] }];
it('shows group and item counts and migrates embedded Wishlist before removing local data', async () => {
  const raw = JSON.stringify({ wallets: [], wishlistGroups });
  localStorage.setItem(STORAGE_KEY, raw);
  let finish;
  migrateData.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  const onComplete = vi.fn();
  render(<DataMigrator onComplete={onComplete} />);
  expect(screen.getByText('1 kelompok wishlist')).toBeInTheDocument();
  expect(screen.getByText('1 item wishlist')).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Pindahkan Data' }));
  expect(migrateData).toHaveBeenCalledWith(expect.objectContaining({ wishlistGroups }));
  expect(localStorage.getItem(STORAGE_KEY)).toBe(raw);
  finish();
  await waitFor(() => expect(onComplete).toHaveBeenCalledTimes(1));
  expect(localStorage.getItem(STORAGE_KEY)).toBeNull();
});
it('offers a visible Wishlist shortcut in Settings without replacing the mobile tabs', () => {
  const setPage = vi.fn();
  render(<SettingsPage setPage={setPage} />);
  const shortcut = screen.getByRole('button', { name: 'Wishlist' });
  expect(shortcut).toBeVisible();
  fireEvent.click(shortcut);
  expect(setPage).toHaveBeenCalledWith('wishlist');
});
it('includes embedded Wishlist in both Settings export payloads', async () => {
  render(<SettingsPage wishlistGroups={wishlistGroups} />);
  fireEvent.click(screen.getByRole('button', { name: 'Ekspor', exact: true }));
  await waitFor(() => expect(downloadJson).toHaveBeenCalledOnce());
  expect(normalizeBackupData).toHaveBeenCalledWith(expect.objectContaining({ wishlistGroups }));
  expect(downloadJson.mock.calls[0][0].data.wishlistGroups).toEqual(wishlistGroups);
  fireEvent.click(screen.getByRole('radio', { name: 'CSV (ZIP)', exact: true }));
  fireEvent.click(screen.getByRole('button', { name: 'Ekspor', exact: true }));
  await waitFor(() => expect(downloadCsvZip).toHaveBeenCalledOnce());
  expect(downloadCsvZip.mock.calls[0][0].wishlistGroups).toEqual(wishlistGroups);
});
it('retains the local Wishlist when migration is pending or fails, even if the dialog close is clicked', async () => {
  const raw = JSON.stringify({ wishlistGroups });
  localStorage.setItem(STORAGE_KEY, raw);
  let reject;
  migrateData.mockImplementation(() => new Promise((resolve, fail) => { reject = fail; }));
  const onComplete = vi.fn();
  render(<DataMigrator onComplete={onComplete} />);
  fireEvent.click(screen.getByRole('button', { name: 'Pindahkan Data' }));
  fireEvent.click(screen.getByRole('button', { name: 'Tutup' }));
  expect(localStorage.getItem(STORAGE_KEY)).toBe(raw);
  expect(onComplete).not.toHaveBeenCalled();
  reject(new Error('migration failed'));
  await screen.findByText('migration failed');
  expect(localStorage.getItem(STORAGE_KEY)).toBe(raw);
  expect(onComplete).not.toHaveBeenCalled();
  expect(screen.getByRole('button', { name: 'Pindahkan Data' })).toBeEnabled();
});
